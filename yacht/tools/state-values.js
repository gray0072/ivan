'use strict';

// Yacht — writes data/state-values.js: for every set of free rows, the points a player can expect
// from those rows with the best play. Nothing on the sheet carries over (no bonus depends on a sum),
// so the free rows are all that matters and 2^15 sets can be solved exactly, from the fewest rows up.
// Run it after a rule's numbers change: node yacht/tools/state-values.js. Not loaded by the game.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const game = vm.runInThisContext('(function () {' + read('constants.js') + read('data/rows.js') + read('sim/scoring.js') +
  ';return { DICE_COUNT, ALL_ROWS, rowScore, diceCounts }; })()');
const { DICE_COUNT, ALL_ROWS, rowScore, diceCounts } = game;

// every sorted set of k dice with its probability
const factorial = [1, 1, 2, 6, 24, 120];
const outcomes = [];
for (let k = 0; k <= DICE_COUNT; k++) {
  const list = [];
  (function walk(start, cur) {
    if (cur.length === k) {
      const n = diceCounts(cur);
      let ways = factorial[k];
      for (let f = 1; f <= 6; f++) ways /= factorial[n[f]];
      list.push({ dice: cur.slice(), weight: ways / Math.pow(6, k) });
      return;
    }
    for (let f = start; f <= 6; f++) { cur.push(f); walk(f, cur); cur.pop(); }
  })(1, []);
  outcomes[k] = list;
}

const keyOf = (dice) => dice.slice().sort((a, b) => a - b).join('');
const SETS = outcomes[DICE_COUNT];
const SET_INDEX = {};
SETS.forEach((s, i) => { SET_INDEX[keyOf(s.dice)] = i; });

// the kept sets (never all five: a roll needs at least one die) and what a roll of the others gives
const HOLDS = [];
const HOLD_INDEX = {};
for (let h = 0; h < DICE_COUNT; h++) {
  for (const held of outcomes[h]) {
    HOLD_INDEX[keyOf(held.dice)] = HOLDS.length;
    HOLDS.push(outcomes[DICE_COUNT - h].map((o) => ({ set: SET_INDEX[keyOf(held.dice.concat(o.dice))], weight: o.weight })));
  }
}
const SET_HOLDS = SETS.map((s) => {
  const seen = new Set();
  for (let mask = 0; mask < 31; mask++) seen.add(HOLD_INDEX[keyOf(s.dice.filter((d, i) => mask & (1 << i)))]);
  return [...seen];
});

// a row's points for each set, after a first roll and after a later one
const POINTS_FIRST = ALL_ROWS.map((r) => SETS.map((s) => rowScore(r.id, s.dice, 1).p));
const POINTS_LATER = ALL_ROWS.map((r) => SETS.map((s) => rowScore(r.id, s.dice, 2).p));

const RN = ALL_ROWS.length;
const values = new Float64Array(1 << RN);
const holdValues = new Float64Array(HOLDS.length);

function fillHolds(from) {
  for (let i = 0; i < HOLDS.length; i++) {
    let v = 0;
    for (const n of HOLDS[i]) v += n.weight * from[n.set];
    holdValues[i] = v;
  }
}
function improve(into) {
  for (let i = 0; i < SETS.length; i++) {
    for (const h of SET_HOLDS[i]) if (holdValues[h] > into[i]) into[i] = holdValues[h];
  }
}

const first = new Float64Array(SETS.length);
const after2 = new Float64Array(SETS.length);
const after3 = new Float64Array(SETS.length);
for (let mask = 1; mask < values.length; mask++) {
  first.fill(-Infinity);
  after3.fill(-Infinity);
  for (let r = 0; r < RN; r++) {
    if (!(mask & (1 << r))) continue;
    const rest = values[mask ^ (1 << r)];
    for (let i = 0; i < SETS.length; i++) {
      const later = POINTS_LATER[r][i] + rest;
      if (later > after3[i]) after3[i] = later;
      const now = POINTS_FIRST[r][i] + rest;
      if (now > first[i]) first[i] = now;
    }
  }
  after2.set(after3);
  fillHolds(after3);
  improve(after2);
  fillHolds(after2);
  improve(first);
  let v = 0;
  for (let i = 0; i < SETS.length; i++) v += SETS[i].weight * first[i];
  values[mask] = v;
}

// two characters a value, in tenths of a point, from STATE_VALUE_MIN up
const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
let lo = Infinity, hi = -Infinity;
for (const v of values) { if (v < lo) lo = v; if (v > hi) hi = v; }
const min = Math.floor(lo);
if ((hi - min) * 10 >= 64 * 64) throw new Error('the values do not fit: ' + lo + ' to ' + hi);
let text = '';
for (const v of values) {
  const t = Math.round((v - min) * 10);
  text += ALPHABET[t >> 6] + ALPHABET[t & 63];
}

fs.writeFileSync(path.join(root, 'data/state-values.js'),
  "'use strict';\n\n" +
  '// Yacht — the points a player can expect from their free rows with the best play, for every set of\n' +
  '// free rows (bit i set: ALL_ROWS[i] is free). Two characters a value, tenths of a point, above\n' +
  '// STATE_VALUE_MIN. Generated by tools/state-values.js, never edited by hand; read by sim/advisor.js.\n\n' +
  'const STATE_VALUE_MIN = ' + min + ';\n' +
  "const STATE_VALUE_ALPHABET = '" + ALPHABET + "';\n" +
  "const STATE_VALUES = '" + text + "';\n");
console.log('all rows free:', values[values.length - 1].toFixed(2), ' range', lo.toFixed(1), 'to', hi.toFixed(1), ' file', text.length, 'chars');
