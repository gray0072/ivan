#!/usr/bin/env node
'use strict';

// Packs the drawings a project needs: finds every arrow, symbol and emoji typed in its code and translations,
// writes them to its data/icons.js and copies the engine (tools/icons/engine.js) to its core/icons.js (a project
// with no data/ or core/ folder: icons-data.js and icons.js in its root). A one-colour drawing comes from
// tools/icons/mono.js; an emoji from tools/icons/color/, fetched once from Twemoji when it is new. It also stops
// on what the engine cannot reach: such a character in a CSS `content` or in a fillText call.
//
// Usage: node tools/icons-build.js <folder>...          write the files; say if they changed: bump their ?v=N
//        node tools/icons-build.js --check <folder>...  change nothing, exit 1 if anything is out of date

const fs = require('fs'), path = require('path');

const repo = path.resolve(__dirname, '..');
const MONO = require('./icons/mono.js');
const COLOR_DIR = path.join(__dirname, 'icons', 'color');
const CDN = 'https://cdn.jsdelivr.net/gh/jdecked/twemoji@latest/assets/svg/';
const GLYPH = /[←-⇿⌀-⏿①-⓿■-➿⤀-⧿⬀-⯿]|[\u{1F000}-\u{1FAFF}]/gu;
const SKIP_DIRS = new Set(['lib', 'tools', 'node_modules', 'supabase']);
const SKIP_FILES = new Set(['icons.js', 'icons-data.js', 'geodata.js', 'state-values.js']);

function sourceFiles(dir, out = []) {
  for (const n of fs.readdirSync(dir)) {
    const p = path.join(dir, n);
    if (fs.statSync(p).isDirectory()) { if (!SKIP_DIRS.has(n)) sourceFiles(p, out); } else if (/\.(js|html|css)$/.test(n) && !SKIP_FILES.has(n)) out.push(p);
  }
  return out;
}

// the code of a line without its comment; a // inside a text or a URL stays
function code(line) {
  return line.replace(/\/\*.*?\*\//g, '').replace(/\/\*.*$/, '').replace(/^\s*\/\/.*$/, '').replace(/^\s*\*.*$/, '').replace(/(^|[^:'"`\\])\/\/ .*$/, '$1');
}

function monoSvg(d) {
  const inner = d.x || (d.f ? '<path fill="#000" d="' + d.f + '"/>'
    : '<path fill="none" stroke="#000" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round" ' + (d.a ? d.a + ' ' : '') + 'd="' + d.s + '"/>');
  // a later stroke-width wins nothing in XML: an attribute may come only once
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">' + inner + '</svg>';
  return d.a ? svg.replace('stroke-width="2.4" ', '') : svg;
}

async function colorSvg(g, check) {
  const hex = g.codePointAt(0).toString(16);
  const file = path.join(COLOR_DIR, hex + '.svg');
  if (fs.existsSync(file)) return fs.readFileSync(file, 'utf8').trim();
  if (check) return null;
  const res = await fetch(CDN + hex + '.svg');
  if (!res.ok) return null;
  const svg = (await res.text()).trim();
  fs.mkdirSync(COLOR_DIR, { recursive: true });
  fs.writeFileSync(file, svg + '\n');
  return svg;
}

function writeIfChanged(file, text, check) {
  const was = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (was === text) return false;
  if (!check) fs.writeFileSync(file, text);
  return true;
}

async function build(folder, check) {
  const dir = path.resolve(repo, folder);
  const found = new Set(), bad = [];
  for (const f of sourceFiles(dir)) {
    fs.readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
      const c = code(line);
      const m = c.match(GLYPH);
      if (!m) return;
      m.forEach((g) => found.add(g));
      const where = path.relative(repo, f).replace(/\\/g, '/') + ':' + (i + 1);
      if (f.endsWith('.css')) bad.push(where + ' ' + m.join('') + ' in a stylesheet: draw it with a mask');
      else if (/\b(fill|stroke)Text\(/.test(c)) bad.push(where + ' ' + m.join('') + ' on a canvas: use Icons.draw or Icons.drawText');
    });
  }
  const mono = {}, color = {}, missing = [];
  for (const g of [...found].sort((a, b) => a.codePointAt(0) - b.codePointAt(0))) {
    if (MONO[g]) mono[g] = monoSvg(MONO[g]);
    else {
      const svg = await colorSvg(g, check);
      if (svg) color[g] = svg;
      else missing.push(g);
    }
  }
  const lines = (table) => Object.keys(table).map((g) => '    ' + JSON.stringify(g) + ': ' + JSON.stringify(table[g])).join(',\n');
  const data = "'use strict';\n\n" +
    '// The drawings of the arrows, symbols and emoji this game uses, read by the Icons engine. Generated by\n' +
    '// tools/icons-build.js, do not edit. Emoji: Twemoji, (c) Twitter and other contributors, CC-BY 4.0,\n' +
    '// https://github.com/jdecked/twemoji\n\n' +
    'const ICONS = {\n  mono: {\n' + lines(mono) + '\n  },\n  color: {\n' + lines(color) + '\n  }\n};\n';
  const flat = !fs.existsSync(path.join(dir, 'core'));
  const dataFile = path.join(dir, flat ? 'icons-data.js' : 'data/icons.js');
  const engineFile = path.join(dir, flat ? 'icons.js' : 'core/icons.js');
  if (!check) fs.mkdirSync(path.dirname(dataFile), { recursive: true });
  const changed = [];
  if (writeIfChanged(dataFile, data, check)) changed.push(path.relative(dir, dataFile));
  if (writeIfChanged(engineFile, fs.readFileSync(path.join(__dirname, 'icons', 'engine.js'), 'utf8'), check)) changed.push(path.relative(dir, engineFile));
  console.log(folder + ': ' + Object.keys(mono).length + ' mono, ' + Object.keys(color).length + ' colour' + (changed.length ? '; ' + (check ? 'out of date: ' : 'changed, bump ?v=N: ') + changed.join(', ') : ''));
  for (const b of bad) console.log('  ' + b);
  if (missing.length) console.log('  no drawing for: ' + missing.join(' ') + (check ? ' (run without --check to fetch)' : ' (add it to tools/icons/mono.js)'));
  return !bad.length && !missing.length && !(check && changed.length);
}

(async () => {
  const args = process.argv.slice(2);
  const check = args[0] === '--check';
  const folders = check ? args.slice(1) : args;
  if (!folders.length) { console.error('usage: node tools/icons-build.js [--check] <folder>...'); process.exit(2); }
  let ok = true;
  for (const f of folders) if (!await build(f, check)) ok = false;
  process.exit(ok ? 0 : 1);
})();
