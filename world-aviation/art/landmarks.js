// ============================================================
// World Aviation — city symbols
// One silhouette per city (a landmark, an animal, a coat of arms
// motif), drawn in a 100 x 100 box with y down, in one colour
// (fg) with cut-outs in the background colour (bg). Used on the
// terminal banners and the city flags (airport3d.js) and on the
// briefing screen.
// ============================================================

const Landmarks = {
  // draw symbol `id` into g, in a square of `size` px with its top left at (x, y)
  draw(g, id, x, y, size, fg, bg) {
    const fn = LANDMARK_SYMBOLS[id] || LANDMARK_SYMBOLS.star;
    g.save();
    g.translate(x, y);
    g.scale(size / 100, size / 100);
    g.fillStyle = fg; g.strokeStyle = fg;
    g.lineCap = 'round'; g.lineJoin = 'round';
    const d = {
      p(str) { g.fillStyle = fg; g.fill(new Path2D(str), 'evenodd'); },
      b(str) { g.fillStyle = bg; g.fill(new Path2D(str), 'evenodd'); },
      s(str, w) { g.strokeStyle = fg; g.lineWidth = w || 3; g.stroke(new Path2D(str)); },
      sb(str, w) { g.strokeStyle = bg; g.lineWidth = w || 3; g.stroke(new Path2D(str)); },
      c(cx, cy, r) { g.fillStyle = fg; g.beginPath(); g.arc(cx, cy, r, 0, TAU); g.fill(); },
      cb(cx, cy, r) { g.fillStyle = bg; g.beginPath(); g.arc(cx, cy, r, 0, TAU); g.fill(); },
      e(cx, cy, rx, ry, rot) { g.fillStyle = fg; g.beginPath(); g.ellipse(cx, cy, rx, ry, rot || 0, 0, TAU); g.fill(); },
      r(x0, y0, w, h) { g.fillStyle = fg; g.fillRect(x0, y0, w, h); },
      rb(x0, y0, w, h) { g.fillStyle = bg; g.fillRect(x0, y0, w, h); },
      t(text, cx, cy, sz) {
        g.fillStyle = fg; g.font = 'bold ' + sz + 'px Arial, sans-serif';
        g.textAlign = 'center'; g.textBaseline = 'middle'; g.fillText(text, cx, cy);
      }
    };
    fn(d);
    g.restore();
  }
};

// a crown: base at y, width w
function lmCrown(d, cx, y, w) {
  const h = w * 0.62, s = w / 2;
  d.p('M' + (cx - s) + ' ' + y + 'H' + (cx + s) + 'L' + (cx + s * 1.08) + ' ' + (y - h) + 'L' + (cx + s * 0.5) + ' ' + (y - h * 0.45) +
    'L' + cx + ' ' + (y - h * 1.1) + 'L' + (cx - s * 0.5) + ' ' + (y - h * 0.45) + 'L' + (cx - s * 1.08) + ' ' + (y - h) + 'Z');
  d.r(cx - s, y + w * 0.06, w, w * 0.14);
  for (const k of [-1.08, 0, 1.08]) d.c(cx + s * k, y - h * (k ? 1 : 1.1) - w * 0.06, w * 0.07);
}
function lmWaves(d, y, w) {
  d.s('M4 ' + y + ' q8 -6 16 0 t16 0 t16 0 t16 0 t16 0 t16 0', w || 3);
}

